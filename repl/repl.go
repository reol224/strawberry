func Start(in io.Reader, out io.Writer) {
	scanner := bufio.NewScanner(in)

	io.WriteString(out, STRAWBERRY_ASCII_ART)

	for {
		fmt.Print(PROMPT)
		scanned := scanner.Scan()
		if !scanned {
			return
		}

		result, err := interpreter.Run(scanner.Text())
		if err != nil {
			var parseError *interpreter.ParseError
			if errors.As(err, &parseError) {
				printParserErrors(out, parseError.Messages)
			} else {
				fmt.Fprintf(out, "error: %v\n", err)
			}
			continue
		}

		if result != "" {
			io.WriteString(out, result)
			io.WriteString(out, "\n")
		}
	}
}

func printParserErrors(out io.Writer, errors []string) {
	io.WriteString(out, "Whoops! Something is not right!\n")
	io.WriteString(out, "parser error(s):\n")
	for _, msg := range errors {
		io.WriteString(out, "\t"+msg+"\n")
	}
}
